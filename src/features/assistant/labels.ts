export function assistantFieldLabel(field: string) {
  return labels[field] || field.replace(/([a-z])([A-Z])/g, '$1 $2');
}
export function assistantValueLabel(value: unknown) {
  if (typeof value === 'boolean') return value ? 'Sí' : 'No';
  if (value === 'cost_matrix') return 'Matriz de costos';
  if (value === 'direct_watt') return 'Precio directo';
  return typeof value === 'string' ? value : JSON.stringify(value);
}
